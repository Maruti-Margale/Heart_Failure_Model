import pandas as pd

df = pd.read_csv("/content/heart.csv")
df

df.info()

# Encoding
from sklearn.preprocessing import LabelEncoder
labelEncoding = LabelEncoder()

df['Sex'] = labelEncoding.fit_transform(df['Sex'])
df['ExerciseAngina'] = labelEncoding.fit_transform(df['ExerciseAngina'])

one_hot_encoding = pd.get_dummies(df['ChestPainType'],prefix = 'Chest_Pain')

df = pd.concat([df,one_hot_encoding],axis=1)
df

target = df.groupby('ST_Slope')['HeartDisease'].mean()
df['ST_Slope'] = df['ST_Slope'].map(target)

target = df.groupby('RestingECG')['HeartDisease'].mean()
df['RestingECG'] = df['RestingECG'].map(target)
df

df.columns

x = df[['Age', 'Sex', 'RestingBP', 'Cholesterol', 'FastingBS',
       'RestingECG', 'MaxHR', 'ExerciseAngina', 'Oldpeak', 'ST_Slope',
        'Chest_Pain_ASY', 'Chest_Pain_ATA', 'Chest_Pain_NAP',
       'Chest_Pain_TA']]
y = df['HeartDisease']

from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import classification_report,accuracy_score



largest = 0
max_i = 0
for i in range(1000):
  x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2,random_state=i)
  model = KNeighborsClassifier()
  model.fit(x_train,y_train)
  pred = model.predict(x_test)
  accu = accuracy_score(y_test,pred)
  print(i)
  if largest > accu:
    largest = accu
    max_i = i
    model = model.fit(x_train,y_train)
print(largest)
print(max_i)

import pickle
with open('Heart_Failure_Prediction.pkl','wb') as file:
  pickle.dump(model,file)

